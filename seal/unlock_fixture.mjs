// Writes test/unlock_fixture.dart: real transaction bytes in the shapes the backend builds for
// pay-to-read (`unlock_prepare_buy`, `unlock_prepare_gift`), plus tampered ones, for
// test/unlock_verify_test.dart. Run: node unlock_fixture.mjs
import { writeFileSync } from 'node:fs';
import { Transaction } from '@mysten/sui/transactions';
import { toBase64 } from '@mysten/sui/utils';

const PKG = '0x7c07a8df79e3f5b92c3b7352c06bce2b28ba1381d5724af6c3db8d19cef8063d';
const USDC = '0xdba34672e30cb065b1f93e3ab55318768fd6fef66c15942c9f7cb846e2f900e7::usdc::USDC';
const BUYER = '0x' + '11'.repeat(32);
const FRIEND = '0x' + '22'.repeat(32);
const SPONSOR = '0x' + '99'.repeat(32);
const LISTING = '0xcaef2818b9ea95d94ecbe381dd559cc4b55549e2c98def8acda09aef34544948';
const RECEIPT = '0x2fef2b958ea281d0cb070000be86c39734330f0098b87024edf3b2326fd5aed2';
const DIGEST = 'GvnqnAzX8uFiBJ5x1T4DZFLDFY2V3iQMMm1Hhqa6hEK4';

async function done(tx) {
  tx.setSender(BUYER);
  tx.setGasOwner(SPONSOR);
  tx.setGasPrice(1000);
  tx.setGasBudget(20_000_000);
  tx.setGasPayment([{ objectId: '0x' + '98'.repeat(32), version: '5', digest: DIGEST }]);
  return toBase64(await tx.build());
}

function buy({ amount = 1500, to = BUYER, listing = LISTING, pkg = PKG, mutable = true, extra = false, type = USDC }) {
  const tx = new Transaction();
  const w = tx.withdrawal({ amount, type });
  const bal = tx.moveCall({ target: '0x2::balance::redeem_funds', typeArguments: [type], arguments: [w] });
  tx.moveCall({
    target: `${pkg}::unlock::buy_for`, typeArguments: [type],
    arguments: [tx.sharedObjectRef({ objectId: listing, initialSharedVersion: '1076508410', mutable }), bal, tx.pure.address(to)],
  });
  if (extra) tx.transferObjects([tx.objectRef({ objectId: RECEIPT, version: '7', digest: DIGEST })], tx.pure.address(FRIEND));
  return done(tx);
}

function gift({ to = FRIEND, obj = RECEIPT, withMoney = false }) {
  const tx = new Transaction();
  if (withMoney) {
    const w = tx.withdrawal({ amount: 1, type: USDC });
    tx.moveCall({ target: '0x2::balance::redeem_funds', typeArguments: [USDC], arguments: [w] });
  }
  tx.transferObjects([tx.objectRef({ objectId: obj, version: '7', digest: DIGEST })], tx.pure.address(to));
  return done(tx);
}

const f = {
  buyOk: await buy({}),
  buyForFriend: await buy({ to: FRIEND }),
  buyMore: await buy({ amount: 1501 }),
  buyOtherListing: await buy({ listing: '0x' + 'ab'.repeat(32) }),
  buyOtherPackage: await buy({ pkg: '0x' + 'cd'.repeat(32) }),
  buyImmutable: await buy({ mutable: false }),
  buyExtraStep: await buy({ extra: true }),
  giftOk: await gift({}),
  giftOtherPerson: await gift({ to: '0x' + '33'.repeat(32) }),
  giftOtherObject: await gift({ obj: '0x' + '44'.repeat(32) }),
  giftWithMoney: await gift({ withMoney: true }),
};
const lines = Object.entries(f).map(([k, v]) => `const ${k} = '${v}';`);
writeFileSync('../test/unlock_fixture.dart', [
  '// Generated by seal/unlock_fixture.mjs (@mysten/sui 2.39.1). Do not edit.',
  '// ignore_for_file: lines_longer_than_80_chars',
  `const buyer = '${BUYER}';`, `const friend = '${FRIEND}';`,
  `const listing = '${LISTING}';`, `const receipt = '${RECEIPT}';`,
  ...lines, '',
].join('\n'));
console.log('wrote', Object.keys(f).length, 'transactions');
